TITLES=tuple('ABCD')
ORDER=('mattergen_base','mattergen_finetuned','concdvae_base','concdvae_finetuned',
       'crysjepa_base','crysjepa_refined','crystalformer','crystalformer_finetuned',
       'crystalllm','crystalllm_finetuned')
LABELS=('MatterGen base','MatterGen tuned','Con-CDVAE base','Con-CDVAE tuned',
        'Crys-JEPA base','Crys-JEPA refined','CrystalFormer base','CrystalFormer tuned',
        'CrystALLM base','CrystALLM tuned')
DFT_ORDER=('mattergen_base','concdvae_base','crystalformer','crystalllm')


def add_letter(ax, letter):
    """Keep the panel letter left-aligned in Ebrima Regular, 14.5 pt."""
    return ax.set_title(letter,loc='left',pad=10,
                        fontproperties=FontProperties(fname=str(ebrima_font_path()),size=14.5,weight='normal'))


def source_layout(stat,dft):
    """Recover presentation parameters, checking frozen values against the artwork."""
    source=ROOT/'tables/figure_sources/figure4/Figure4_DFT.pdf'
    doc=fitz.open(source)
    page=doc[0]
    paths=page.get_drawings()
    frames=[p['rect'] for p in paths if p['fill']==(1.,1.,1.) and 200<p['rect'].width<page.rect.width*.8]
    assert len(frames)==4
    def bars(frame):
        return sorted([p for p in paths if p['fill'] not in (None,(1.,1.,1.))
                       and len(p['items'])==1 and p['items'][0][0]=='re'
                       and frame.contains(p['rect'])],key=lambda p:p['rect'].y0)
    a,b,c,d=frames
    abars,dbars=bars(a),bars(d)
    assert len(abars)==10 and len(dbars)==4
    colors=[p['fill'] for p in abars]
    np.testing.assert_allclose([(p['rect'].x1-a.x0)/a.width*1.025 for p in abars],
                               stat.fraction_magnetic_like,atol=2e-6,rtol=0)
    np.testing.assert_allclose([(p['rect'].x1-d.x0)/d.width*1.035 for p in dbars],
                               dft.confirmation_fraction,atol=2e-6,rtol=0)
    # B's selected display range is -6..6.4, rather than an auto-scaled range.
    thin=sorted([p for p in paths if p['type']=='s' and b.contains(p['rect'])
                 and abs(p['width']-1.6)<.01],key=lambda p:p['rect'].y0)
    thick=sorted([p for p in paths if p['type']=='s' and b.contains(p['rect'])
                  and abs(p['width']-10)<.01],key=lambda p:p['rect'].y0)
    assert len(thin)==len(thick)==10
    for drawings,columns in ((thin,('contrast_q05','contrast_q95')),
                              (thick,('contrast_q25','contrast_q75'))):
        for side,column in zip(('x0','x1'),columns):
            np.testing.assert_allclose([(getattr(p['rect'],side)-b.x0)/b.width*12.4-6 for p in drawings],
                                       stat[column],atol=5e-6,rtol=0)
    medians=sorted([p for p in paths if b.contains(p['rect']) and p['fill'] is not None
                    and p['rect'].width<.01 and 5<p['rect'].height<20],key=lambda p:p['rect'].y0)
    assert len(medians)==10
    np.testing.assert_allclose([(p['rect'].x0-b.x0)/b.width*12.4-6 for p in medians],
                               stat.contrast_q50,atol=5e-6,rtol=0)
    # Independently check both endpoints of every A/D confidence interval.
    for frame,items,low,high,xmax in ((a,abars,stat.fmag_ci_low,stat.fmag_ci_high,1.025),
                                     (d,dbars,dft.CI95_low,dft.CI95_high,1.035)):
        for bar,lo,hi in zip(items,low,high):
            center=(bar['rect'].y0+bar['rect'].y1)/2
            horizontal=[]
            for p in paths:
                for item in p['items']:
                    if item[0]=='l':
                        start,end=item[1:]
                        if abs(start.y-center)<.01 and abs(end.y-center)<.01 and abs(start.x-end.x)>.01:
                            horizontal.append(sorted(((start.x-frame.x0)/frame.width*xmax,(end.x-frame.x0)/frame.width*xmax)))
            assert any(np.allclose(pair,[lo,hi],atol=5e-6,rtol=0) for pair in horizontal),('CI',lo,hi)
    cpaths=bars(c)
    branch_colors=[]
    for branch in ('AFM','FM','FiM'):
        # PDF bar operators retain branch order; do not sort stacked segments by height.
        groups=[p for p in paths if p in cpaths]
        unique=list(dict.fromkeys(p['fill'] for p in groups))
        color=unique[('AFM','FM','FiM').index(branch)]
        branch_colors.append(color)
        segments=sorted([p for p in groups if p['fill']==color],key=lambda p:p['rect'].x0)
        expected=stat['branch_'+branch].to_numpy()
        actual=np.zeros(10)
        for p in segments:
            center=(p['rect'].x0+p['rect'].x1)/2
            index=round((center-c.x0)/c.width*10.2-.6)
            actual[index]=p['rect'].height/c.height*1.03
        np.testing.assert_allclose(actual,expected,atol=2e-6,rtol=0)
    def geometry(items,frame):
        centers=np.array([(p['rect'].y0+p['rect'].y1)/2 for p in items])
        step=float(np.mean(np.diff(centers)))
        return ((frame.y1-centers[0])/step,(frame.y0-centers[0])/step),items[0]['rect'].height/step
    return page.rect,frames,colors,branch_colors,geometry(abars,a),geometry(dbars,d)


def combined_figure(output,dpi=180):
    data=ROOT/'tables/figure_sources/figure4'
    stat=pd.read_csv(data/'figure_statistics.csv').set_index('dataset').loc[list(ORDER)]
    # Use the audited readbacks of the selected artwork, not the numerically
    # different historical recalculation (notably bootstrap bounds/FT quantiles).
    readback=pd.read_csv(data/'selected_artwork_statistics_readback.csv')
    for row in readback.itertuples():
        if row.panel in ('A','B','C') and row.metric in stat.columns:
            stat.loc[row.dataset,row.metric]=row.original_pdf_readback
    # Reuse the already selected DFT summary, including its Wilson bounds.
    # No moments, labels, thresholds or confidence intervals are recomputed here.
    dft=pd.read_csv(data/'Figure4D_summary.csv').set_index('dataset').loc[list(DFT_ORDER)]
    page,frames,colors,branch_colors,ageom,dgeom=source_layout(stat,dft)
    apply_ebrima_typography()
    plt.rcParams.update({'font.size':9,'axes.labelsize':10,'xtick.labelsize':9,
                         'ytick.labelsize':8.5,'axes.spines.top':False,'axes.spines.right':False,
                         'savefig.facecolor':'white','axes.facecolor':'white'})
    fig=plt.figure(figsize=(page.width/72,page.height/72))
    axes=[fig.add_axes([r.x0/page.width,1-r.y1/page.height,r.width/page.width,r.height/page.height]) for r in frames]
    a,b,c,d=axes
    y=np.arange(10)
    for ax in (a,b):
        ax.set_yticks(y,LABELS)
        ax.tick_params(axis='y',length=0,pad=3)
    for ax in (a,b,d):
        ax.xaxis.grid(True,lw=.6,color='#9099A1',alpha=.17)
        ax.set_axisbelow(True)
    for ax in (a,b):
        for i in range(2,10,2):
            ax.axhline(i-.5,lw=.6,color='#B8C0C4',alpha=.55)
    values=stat.fraction_magnetic_like.to_numpy()
    a.barh(y,values,color=colors,height=ageom[1])
    a.errorbar(values,y,xerr=np.vstack([values-stat.fmag_ci_low,stat.fmag_ci_high-values]),
               fmt='none',ecolor='#303030',lw=.9,capsize=2.5)
    a.set_ylim(*ageom[0]);a.set_xlim(0,1.025);a.set_xticks(np.linspace(0,1,6))
    a.set_xlabel('Fraction closer to magnetic than NM reference')
    for j,(_,row) in enumerate(stat.iterrows()):
        b.plot([row.contrast_q05,row.contrast_q95],[j,j],color=colors[j],lw=1.6)
        b.plot([row.contrast_q25,row.contrast_q75],[j,j],color=colors[j],lw=10,solid_capstyle='butt')
        half=7/(frames[1].height/9.9)
        b.plot([row.contrast_q50]*2,[j-half,j+half],color='#172229',lw=2)
    b.axvline(0,color='#666666',lw=.9)
    b.set_ylim(9.45,-.45);b.set_xlim(-6,6.4);b.set_xticks(np.arange(-6,7,2))
    b.set_xlabel(r'Magnetic-reference contrast, $d_{NM}-d_{mag}$')
    bottom=np.zeros(10)
    for branch,color in zip(('AFM','FM','FiM'),branch_colors):
        vals=stat['branch_'+branch].to_numpy()
        c.bar(y,vals,width=.73,bottom=bottom,color=color,label=branch)
        bottom+=vals
    c.set_ylim(0,1.03);c.set_xlim(-.6,9.6)
    c.set_xticks(y,LABELS,rotation=30,ha='right',rotation_mode='anchor')
    c.tick_params(axis='x',labelsize=7.8)
    c.tick_params(axis='y',labelsize=8.5)
    c.set_ylabel('Fraction among magnetic-like candidates')
    c.yaxis.grid(True,lw=.6,color='#9099A1',alpha=.17);c.set_axisbelow(True)
    # A separate row above C's letter uses the existing inter-row whitespace.
    legend=c.legend(frameon=False,ncol=3,loc='lower right',bbox_to_anchor=(1,1.13),fontsize=8.5)
    values=dft.confirmation_fraction.to_numpy()
    d.barh(np.arange(4),values,color=[colors[ORDER.index(k)] for k in DFT_ORDER],height=dgeom[1])
    d.errorbar(values,np.arange(4),xerr=np.vstack([values-dft.CI95_low,dft.CI95_high-values]),
               fmt='none',ecolor='#303030',lw=1,capsize=2.4)
    d.set_yticks(np.arange(4),[LABELS[ORDER.index(k)] for k in DFT_ORDER])
    d.tick_params(axis='y',length=0,pad=3)
    d.set_ylim(*dgeom[0]);d.set_xlim(0,1.035);d.set_xticks(np.linspace(0,1,6))
    d.set_xlabel(r'Fraction with $|m_{max}| > 0.5$ $\mu_B$ in DFT')
    titles=[add_letter(ax,letter) for ax,letter in zip(axes,TITLES)]
    # Keep the sizes of all other text, including math, unchanged.
    fig.canvas.draw()
    for text in fig.findobj(match=Text):
        text.set_fontproperties(FontProperties(fname=str(ebrima_font_path()),size=text.get_fontsize(),weight='normal'))
    fig.canvas.draw()
    renderer=fig.canvas.get_renderer()
    assert not legend.get_window_extent(renderer).overlaps(titles[2].get_window_extent(renderer))
    for title in titles:
        assert fig.bbox.contains(*title.get_window_extent(renderer).get_points()[0])
        assert fig.bbox.contains(*title.get_window_extent(renderer).get_points()[1])
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    name='fig04_magnetic_reference_dft'
    for ext in ('png','pdf','svg'):
        fig.savefig(output/f'{name}.{ext}',dpi=dpi,bbox_inches='tight',pad_inches=.16)
    plt.close(fig)
    with fitz.open(output/f'{name}.pdf') as doc:
        fix_ebrima_to_unicode(doc)
        doc.save(output/f'{name}_unicode.pdf',garbage=4,deflate=True)
    (output/f'{name}_unicode.pdf').replace(output/f'{name}.pdf')
    doc=fitz.open(output/f'{name}.pdf')
    text=doc[0].get_text()
    for letter in TITLES:
        assert text.splitlines().count(letter)==1
    for f in doc[0].get_fonts():
        base,_,_,blob=doc.extract_font(f[0]);assert 'Ebrima' in base and 'Bold' not in base
        with TTFont(io.BytesIO(blob)) as font:assert font['OS/2'].usWeightClass==400
    for block in doc[0].get_text('dict')['blocks']:
        for line in block.get('lines',[]):
            for span in line['spans']:assert doc[0].rect.contains(fitz.Rect(span['bbox']))
    assert not doc[0].get_images()
    doc[0].get_pixmap(matrix=fitz.Matrix(1.5,1.5)).save(output/'pdf_render.png')
    report={'source_statistics_sha256':hashlib.sha256((data/'figure_statistics.csv').read_bytes()).hexdigest(),
            'selected_artwork_readback_sha256':hashlib.sha256((data/'selected_artwork_statistics_readback.csv').read_bytes()).hexdigest(),
            'frozen_dft_summary_sha256':hashlib.sha256((data/'Figure4D_summary.csv').read_bytes()).hexdigest(),
            'titles':list(TITLES),'font':'Ebrima Regular','title_size_pt':14.5,
            'source_numeric_comparison':'PASS','dft_recalculated':False,
            'legend_title_overlap':False,'vector_pdf':True}
    (output/'figure4_panel_titles_verification.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report,indent=2))


